#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
luci_pkg.py —— OpenWrt LuCI 主题包「多架构」检查 / 改包工具

支持两种包格式:
  ipk : OpenWrt <= 24.10 (opkg)。外层 tar[.gz] 内含
        debian-binary / control.tar.{gz,xz} / data.tar.{gz,xz}
  apk : OpenWrt >= 25.0 (apk-tools, APK v2)。gzip 包裹的「多段 tar」:
        [ .SIGN.RSA* 签名段 ] + [ .PKGINFO 控制段(+安装脚本) ] + [ 数据段 ]

用法:
  python luci_pkg.py inspect  <pkg>
  python luci_pkg.py repack   <pkg> [-o OUT] [--arch all|noarch] [--force]

设计要点:
  * 只改「控制信息里的架构字段」，数据段字节原样保留（apk 的 datahash 才不会失效）。
  * 同时扫描包内是否真的含架构相关文件（ELF / .so / Go 二进制），这才是「多架构」的真门槛。
  * 重新打包后签名必然失效：ipk 无所谓；apk 需要 --allow-untrusted 或自建签名。
"""
from __future__ import annotations

import argparse
import gzip
import hashlib
import io
import lzma
import os
import re
import struct
import sys
import tarfile

ELF_MACHINE = {
    2: "SPARC", 3: "i386", 8: "MIPS", 20: "PowerPC", 21: "PowerPC64", 22: "S390",
    40: "ARM", 42: "SuperH", 50: "IA-64", 62: "x86-64", 183: "AArch64", 243: "RISC-V",
}
BLOCK = 512


# ----------------------------------------------------------------------------- utils
def gunzip_auto(raw: bytes) -> bytes:
    return gzip.decompress(raw) if raw[:2] == b"\x1f\x8b" else raw


def gz(data: bytes) -> bytes:
    buf = io.BytesIO()
    with gzip.GzipFile(fileobj=buf, mode="wb", compresslevel=9, mtime=0) as f:
        f.write(data)
    return buf.getvalue()


def decompress_member(name: str, data: bytes) -> tuple[str, bytes]:
    if name.endswith(".gz"):
        return "gz", gzip.decompress(data)
    if name.endswith(".xz"):
        return "xz", lzma.decompress(data)
    return "plain", data


def compress_member(kind: str, plain: bytes) -> bytes:
    if kind == "gz":
        return gz(plain)
    if kind == "xz":
        return lzma.compress(plain, preset=6)
    return plain


def read_tar(raw: bytes):
    """返回 [(TarInfo, bytes)]，用于解析小体量 tar 段。"""
    out = []
    with tarfile.open(fileobj=io.BytesIO(raw), mode="r:") as tf:
        for ti in tf:
            data = b""
            if ti.isreg():
                f = tf.extractfile(ti)
                if f is not None:
                    data = f.read()
            out.append((ti, data))
    return out


def build_tar(entries, fmt=tarfile.GNU_FORMAT) -> bytes:
    """entries: [(name, data, mode)]"""
    buf = io.BytesIO()
    with tarfile.open(fileobj=buf, mode="w", format=fmt) as tf:
        for name, data, mode in entries:
            ti = tarfile.TarInfo(name)
            ti.size = len(data)
            ti.mtime = 0
            ti.mode = mode
            ti.uid = ti.gid = 0
            ti.uname = ti.gname = "root"
            tf.addfile(ti, io.BytesIO(data))
    return buf.getvalue()


# ------------------------------------------------------------------- apk 分段解析
def split_tar_segments(raw: bytes):
    """把 gzip 解出来的连续 tar 切成若干段（apk v2 用 tar 的 EOF 块分隔各段）。"""
    segs, start, off, n = [], 0, 0, len(raw)
    while off + BLOCK <= n:
        block = raw[off:off + BLOCK]
        if block.strip(b"\0") == b"":
            p = off
            while p + BLOCK <= n and raw[p:p + BLOCK].strip(b"\0") == b"":
                p += BLOCK
            segs.append(raw[start:p])
            off = start = p
            continue
        try:
            size = int(block[124:136].strip(b"\0 ") or b"0", 8)
        except ValueError:
            raise ValueError("偏移 %d 处不是合法 tar 头" % off)
        off += BLOCK + ((size + BLOCK - 1) // BLOCK) * BLOCK
    if start < n:
        segs.append(raw[start:n])
    return [s for s in segs if s.strip(b"\0")]


def parse_pkginfo(text: str) -> dict:
    meta = {}
    for line in text.splitlines():
        line = line.strip()
        if not line or line.startswith("#"):
            continue
        if "=" in line:
            k, v = line.split("=", 1)
            meta.setdefault(k.strip(), []).append(v.strip())
    return meta


def pkginfo_text(meta: dict, order: list[str]) -> str:
    lines = ["# Generated by luci_pkg.py repack"]
    for k in order:
        for v in meta.get(k, []):
            lines.append("%s = %s" % (k, v))
    for k in meta:
        if k not in order:
            for v in meta[k]:
                lines.append("%s = %s" % (k, v))
    return "\n".join(lines) + "\n"


# ------------------------------------------------------------------ 架构相关文件扫描
def elf_desc(data: bytes) -> str | None:
    if len(data) < 20 or data[:4] != b"\x7fELF":
        return None
    cls = "64-bit" if data[4] == 2 else "32-bit"
    endian = "LE" if data[5] == 1 else "BE"
    machine = struct.unpack("<H" if data[5] == 1 else ">H", data[18:20])[0]
    return "%s %s %s" % (cls, endian, ELF_MACHINE.get(machine, "machine#%d" % machine))


# ------------------------------------------------------------------------- 读取包
class Package:
    def __init__(self, path: str):
        self.path = path
        self.raw = open(path, "rb").read()
        self.format = None
        self.arch = None
        self.name = None
        self.version = None
        self.meta = {}
        self.files = []          # [(path, bytes)]
        self.scripts = []        # [name]
        self.signed = False
        self.datahash_ok = None
        self._ipk = None
        self._apk = None
        self._read()

    # ---- 判定格式
    def _read(self):
        if self.raw[:8] == b"!<arch>\n":
            raise SystemExit("这是 Debian 风格的 ar 包，本工具暂不支持")
        if self.raw[:3] == b"ADB":
            kind = {b"ADB.": "未压缩", b"ADBd": "deflate 压缩", b"ADBc": "带压缩头的压缩"}.get(
                self.raw[:4], "未知子类型")
            raise SystemExit(
                "这是 apk-tools 3.x 的 v3 包（ADB 容器，%s），OpenWrt 25.x 用的就是它。\n"
                "本工具的 ipk / apk-v2 逻辑处理不了 v3，请用 apk-tools 自带命令：\n"
                "  查看: apk adbdump %s\n"
                "  解开: mkdir -p tree && cd tree && apk --allow-untrusted extract %s\n"
                "解出来的目录可以直接 build 成 opkg 固件用的 ipk。"
                % (kind, self.path, self.path))
        inner = gunzip_auto(self.raw)
        # ipk 只有一个 tar；apk 是「多段 tar」，tarfile 只会读到第一段，
        # 所以 apk 分支要先把段切开再判断。
        members, names = [], []
        try:
            members = read_tar(inner)
            names = [ti.name for ti, _ in members]
        except Exception:
            names = []
        if any(n.endswith("PKGINFO") for n in names) or any(
                n.lstrip("./").startswith("control.tar") for n in names):
            pass
        else:
            try:
                segs = split_tar_segments(inner)
            except Exception:
                segs = []
            seg_names = []
            for seg in segs:
                try:
                    seg_names += [ti.name for ti, _ in read_tar(seg)]
                except Exception:
                    pass
            names = seg_names
        if any(n.endswith("control.tar.gz") or n.endswith("control.tar.xz") or
               n.endswith("control.tar") for n in names):
            self._read_ipk(members)
        elif any(n.endswith("PKGINFO") for n in names):
            self._read_apk(inner)
        else:
            raise SystemExit(
                "无法解析为 ipk/apk：文件头 %s，成员 %s。"
                "这很可能不是有效包（加密、损坏或下载不完整）。"
                % (self.raw[:16].hex(), ", ".join(names[:8]) or "(空)")
            )

    def _read_ipk(self, members):
        self.format = "ipk"
        ctl_name = ctl_kind = None
        data_name = data_kind = None
        for ti, data in members:
            n = ti.name.lstrip("./")
            if n.startswith("control.tar"):
                ctl_name, (ctl_kind, ctl_plain) = n, decompress_member(n, data)
            elif n.startswith("data.tar"):
                data_name, (data_kind, data_plain) = n, decompress_member(n, data)
        if not ctl_name:
            raise SystemExit("ipk 缺少 control.tar.*")
        self._ipk = {"ctl_name": ctl_name, "ctl_kind": ctl_kind,
                     "data_name": data_name, "data_kind": data_kind,
                     "data_plain": data_plain}
        for ti, data in read_tar(ctl_plain):
            base = os.path.basename(ti.name)
            if base == "control":
                text = data.decode("utf-8", "replace")
                self._parse_control(text)
        if data_plain:
            for ti, data in read_tar(data_plain):
                if ti.isreg():
                    self.files.append((ti.name.lstrip("./"), data))

    def _parse_control(self, text: str):
        lines = text.splitlines()
        for i, line in enumerate(lines):
            if line.startswith("Architecture:"):
                self.arch = line.split(":", 1)[1].strip()
        for line in lines:
            if ":" in line and not line.startswith(" "):
                k, v = line.split(":", 1)
                self.meta[k.strip()] = v.strip()
        self.name = self.meta.get("Package")
        self.version = self.meta.get("Version")

    def _read_apk(self, inner: bytes):
        self.format = "apk"
        segs = split_tar_segments(inner)
        ctl_seg = None
        for seg in segs:
            names = [ti.name for ti, _ in read_tar(seg)]
            if any(".SIGN." in n for n in names):
                self.signed = True
            if any(n.endswith("PKGINFO") for n in names):
                ctl_seg = seg
                self._apk = {"ctl_seg": seg,
                             "data_seg": inner[inner.index(seg) + len(seg):]}
                break
        if ctl_seg is None:
            raise SystemExit("apk 缺少 .PKGINFO 段")
        ctl_members = read_tar(ctl_seg)
        pkginfo = b""
        for ti, data in ctl_members:
            base = os.path.basename(ti.name)
            if base == ".PKGINFO":
                pkginfo = data
            elif base.startswith("."):
                self.scripts.append(base)
        self.meta = parse_pkginfo(pkginfo.decode("utf-8", "replace"))
        self.name = (self.meta.get("pkgname") or [None])[0]
        self.version = (self.meta.get("pkgver") or [None])[0]
        self.arch = (self.meta.get("arch") or [None])[0]
        data_seg = self._apk["data_seg"]
        if data_seg:
            for ti, data in read_tar(data_seg):
                if ti.isreg():
                    self.files.append((ti.name.lstrip("./"), data))
        claimed = (self.meta.get("datahash") or [None])[0]
        if claimed and data_seg:
            actual = hashlib.sha256(data_seg).hexdigest()
            self.datahash_ok = (actual == claimed)

    # ---- 报告
    def arch_risks(self):
        risks = []
        for path, data in self.files:
            d = elf_desc(data)
            if d:
                risks.append((path, d))
            elif path.endswith(".so"):
                risks.append((path, "文件名像共享库，但头不是 ELF（可能是占位/文本）"))
        return risks

    def report(self) -> str:
        out = []
        out.append("文件        : %s" % self.path)
        out.append("格式        : %s (%s)" % (self.format, "opkg/ipk" if self.format == "ipk" else "apk-tools v2"))
        out.append("包名        : %s" % self.name)
        out.append("版本        : %s" % self.version)
        out.append("声明架构    : %s" % self.arch)
        if self.format == "ipk":
            ds = self.meta.get("Depends", "")
            out.append("依赖        : %s" % (ds or "(无)"))
            out.append("Installed-Size: %s KB" % self.meta.get("Installed-Size", "?"))
        else:
            deps = ", ".join(self.meta.get("depend", [])) or "(无)"
            out.append("依赖        : %s" % deps)
            out.append("签名        : %s" % ("有（改包后会失效）" if self.signed else "无"))
            if self.datahash_ok is not None:
                out.append("datahash 校验: %s" % ("通过" if self.datahash_ok else "不匹配（分段解析可能不对，慎改）"))
            out.append("安装脚本    : %s" % (", ".join(self.scripts) or "(无)"))
        out.append("文件数      : %d" % len(self.files))
        for p, _ in self.files[:8]:
            out.append("   - %s" % p)
        if len(self.files) > 8:
            out.append("   ... 共 %d 个" % len(self.files))

        risks = self.arch_risks()
        out.append("")
        if risks:
            out.append("架构相关文件（这是真正妨碍多架构的东西）:")
            for p, d in risks:
                out.append("  ! %-60s %s" % (p, d))
        else:
            out.append("架构相关文件: 无 —— 纯静态资源，改成 all/noarch 即可跨架构安装")
        return "\n".join(out)


# ------------------------------------------------------------------------- 重新打包
def repack_ipk(pkg: Package, arch: str) -> bytes:
    ctl_plain = pkg._ipk["ctl_plain"] if "ctl_plain" in pkg._ipk else None
    if ctl_plain is None:
        # 重新解析一次控制段
        raw = gunzip_auto(pkg.raw)
        for ti, data in read_tar(raw):
            n = ti.name.lstrip("./")
            if n.startswith("control.tar"):
                ctl_plain = decompress_member(n, data)[1]
    entries = []
    for ti, data in read_tar(ctl_plain):
        base = os.path.basename(ti.name)
        mode = ti.mode or 0o644
        if base == "control":
            text = data.decode("utf-8")
            if re.search(r"^Architecture:.*$", text, re.M):
                text = re.sub(r"^Architecture:.*$", "Architecture: %s" % arch, text, flags=re.M)
            else:
                text += "\nArchitecture: %s\n" % arch
            data = text.encode("utf-8")
        entries.append((ti.name, data, mode))
    new_ctl = build_tar(entries)

    outer = []
    raw = gunzip_auto(pkg.raw)
    for ti, data in read_tar(raw):
        n = ti.name.lstrip("./")
        if n.startswith("control.tar"):
            kind = decompress_member(n, data)[0]
            outer.append((ti.name, compress_member(kind, new_ctl), ti.mode or 0o644))
        else:
            outer.append((ti.name, data, ti.mode or 0o644))
    return gz(build_tar(outer))


def repack_apk(pkg: Package, arch: str) -> bytes:
    ctl_seg = pkg._apk["ctl_seg"]
    data_seg = pkg._apk["data_seg"]
    entries = []
    for ti, data in read_tar(ctl_seg):
        base = os.path.basename(ti.name)
        if base == ".PKGINFO":
            meta = {k: list(v) for k, v in pkg.meta.items()}
            meta["arch"] = [arch]
            order = [k for k in pkg.meta if k != "arch"]
            idx = order.index("pkgdesc") if "pkgdesc" in order else 0
            order.insert(idx, "arch")
            data = pkginfo_text(meta, order).encode("utf-8")
        entries.append((ti.name, data, ti.mode or 0o644))
    new_ctl = build_tar(entries)
    return gz(new_ctl + data_seg)


CTL_DIR = "_luci_pkg_control"
SCRIPT_MAP = {
    "pre-install": "preinst", "post-install": "postinst",
    "pre-deinstall": "prerm", "post-deinstall": "postrm",
}


def extract_pkg(pkg: Package, dest: str) -> int:
    n = 0
    for path, data in pkg.files:
        full = os.path.join(dest, path.replace("/", os.sep))
        os.makedirs(os.path.dirname(full) or dest, exist_ok=True)
        with open(full, "wb") as f:
            f.write(data)
        n += 1
    # 安装脚本单独放，避免混进数据段
    if pkg.format == "apk":
        ctl_dir = os.path.join(dest, CTL_DIR)
        for ti, data in read_tar(pkg._apk["ctl_seg"]):
            base = os.path.basename(ti.name)
            if base.startswith(".") and base != ".PKGINFO":
                os.makedirs(ctl_dir, exist_ok=True)
                with open(os.path.join(ctl_dir, base.lstrip(".")), "wb") as f:
                    f.write(data)
    return n


def build_pkg(root: str, fmt: str, name: str, version: str, arch: str,
              depends: str, desc: str) -> bytes:
    entries = []
    scripts = {}
    for dirpath, _dirs, files in os.walk(root):
        for fn in files:
            full = os.path.join(dirpath, fn)
            rel = os.path.relpath(full, root).replace(os.sep, "/")
            data = open(full, "rb").read()
            if rel.startswith(CTL_DIR + "/"):
                scripts[rel[len(CTL_DIR) + 1:]] = data
                continue
            mode = 0o755 if data.startswith(b"#!") else 0o644
            entries.append((rel, data, mode))
    entries.sort()
    data_tar = build_tar(entries)
    deps = [d.strip() for d in depends.replace(",", " ").split() if d.strip()]

    if fmt == "ipk":
        fields = [
            "Package: %s" % name,
            "Version: %s" % version,
            "Depends: %s" % ", ".join(deps) if deps else "",
            "Architecture: %s" % arch,
            "Installed-Size: %d" % (len(data_tar) // 1024 + 1),
            "Description: %s" % desc,
        ]
        ctl_text = "\n".join(x for x in fields if x) + "\n"
        ctl_entries = [("control", ctl_text.encode(), 0o644), ("conffiles", b"", 0o644)]
        for k, v in sorted(scripts.items()):
            ctl_entries.append((SCRIPT_MAP.get(k, k), v, 0o755))
        ctl = build_tar(ctl_entries)
        outer = build_tar([
            ("debian-binary", b"2.0\n", 0o644),
            ("./control.tar.gz", gz(ctl), 0o644),
            ("./data.tar.gz", gz(data_tar), 0o644),
        ])
        return gz(outer)

    pkginfo = "\n".join([
        "# Generated by luci_pkg.py build",
        "pkgname = %s" % name,
        "pkgver = %s" % version,
        "pkgdesc = %s" % desc,
        "arch = %s" % arch,
        "size = %d" % len(data_tar),
        "origin = %s" % name,
        "license = unknown",
    ] + ["depend = %s" % d for d in deps] + [
        "datahash = %s" % hashlib.sha256(data_tar).hexdigest(),
    ]) + "\n"
    ctl_entries = [(".PKGINFO", pkginfo.encode(), 0o644)]
    for k, v in sorted(scripts.items()):
        ctl_entries.append(("." + k, v, 0o755))
    ctl = build_tar(ctl_entries)
    return gz(ctl + data_tar)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description="OpenWrt LuCI 包多架构检查/改包")
    sub = ap.add_subparsers(dest="cmd", required=True)

    p1 = sub.add_parser("inspect", help="查看包结构、架构、架构相关文件")
    p1.add_argument("pkg")

    p2 = sub.add_parser("repack", help="把架构字段改成 all/noarch")
    p2.add_argument("pkg")
    p2.add_argument("-o", "--out", help="输出文件路径")
    p2.add_argument("--arch", help="目标架构值，默认 ipk=all / apk=noarch")
    p2.add_argument("--force", action="store_true", help="即使发现 ELF/.so 也照样改")

    p3 = sub.add_parser("extract", help="把包内文件解到目录（闭源包改壳用）")
    p3.add_argument("pkg")
    p3.add_argument("-d", "--dest", default="extracted")

    p4 = sub.add_parser("build", help="从目录重新打一个 all/noarch 包")
    p4.add_argument("dir")
    p4.add_argument("-o", "--out", required=True)
    p4.add_argument("--format", choices=["ipk", "apk"], default="ipk")
    p4.add_argument("--name", required=True)
    p4.add_argument("--version", default="1.0.0")
    p4.add_argument("--arch", default=None)
    p4.add_argument("--depends", default="luci-base")
    p4.add_argument("--desc", default="")

    a = ap.parse_args(argv)

    if a.cmd == "build":
        arch = a.arch or ("noarch" if a.format == "apk" else "all")
        blob = build_pkg(a.dir, a.format, a.name, a.version, arch, a.depends, a.desc)
        with open(a.out, "wb") as f:
            f.write(blob)
        print("已写出: %s (%d 字节, arch=%s)" % (a.out, len(blob), arch))
        if a.format == "apk":
            print("未签名，安装用  apk add --allow-untrusted %s" % os.path.basename(a.out))
        return 0

    pkg = Package(a.pkg)

    if a.cmd == "extract":
        n = extract_pkg(pkg, a.dest)
        print("已解出 %d 个文件到 %s" % (n, os.path.abspath(a.dest)))
        return 0

    if a.cmd == "inspect":
        print(pkg.report())
        return 0

    risks = pkg.arch_risks()
    if risks and not a.force:
        print(pkg.report())
        print("\n发现 %d 个架构相关文件，改 arch 字段也无法跨架构运行。" % len(risks))
        print("确认只是想让包能装上（运行时另想办法），可加 --force。")
        return 2

    arch = a.arch or ("noarch" if pkg.format == "apk" else "all")
    blob = repack_apk(pkg, arch) if pkg.format == "apk" else repack_ipk(pkg, arch)
    out = a.out or os.path.join(
        os.path.dirname(os.path.abspath(a.pkg)),
        "%s_%s.%s" % (pkg.name or "pkg", arch, pkg.format),
    )
    with open(out, "wb") as f:
        f.write(blob)
    print("已写出: %s (%d 字节, arch=%s)" % (out, len(blob), arch))
    if pkg.format == "apk":
        print("注意: 签名已失效，安装用  apk add --allow-untrusted %s" % os.path.basename(out))
    else:
        print("安装:  opkg install %s" % os.path.basename(out))
    return 0


if __name__ == "__main__":
    sys.exit(main())
