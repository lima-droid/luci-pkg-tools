#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""生成测试用的假 ipk / apk，验证 luci_pkg.py 的 inspect / repack 行为。"""
import gzip, hashlib, io, os, sys, tarfile

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from luci_pkg import build_tar, gz  # noqa: E402

FIX = os.path.join(os.path.dirname(HERE), "examples")
os.makedirs(FIX, exist_ok=True)

CSS = b"/* ctmodem theme */\nbody{background:#0b1c2c}\n" * 8
TPL = b'<%+header%>\n<div class="ctmodem-{{board}}">{{msg}}</div>\n<%+footer%>\n'
ELF64 = (b"\x7fELF\x02\x01\x01\x00" + b"\x00" * 8 + b"\x02\x00\x3e\x00" + b"\x00" * 40
         + b"fake-aarch64-or-x86-binary-payload" * 4)


def tar(entries):
    return build_tar([(n, d, m) for n, d, m in entries])


def make_ipk(path, arch, extra=()):
    control = (
        "Package: luci-theme-ctmodem\n"
        "Version: 26.293.25639~e74b366\n"
        "Depends: luci-base, luci-compat\n"
        "Conflicts: luci-theme-bootstrap\n"
        "Source: feeds/luci/themes/luci-theme-ctmodem\n"
        "SourceName: luci-theme-ctmodem\n"
        "License: Apache-2.0\n"
        "Section: luci\n"
        "Architecture: %s\n"
        "Installed-Size: 118\n"
        "Description: CT modem theme for LuCI\n" % arch
    ).encode()
    ctl = tar([("control", control, 0o644), ("conffiles", b"", 0o644)])
    data = tar([
        ("www/luci-static/ctmodem/style.css", CSS, 0o644),
        ("usr/share/ucode/luci/template/themes/ctmodem/header.ut", TPL, 0o644),
        *extra,
    ])
    outer = tar([
        ("debian-binary", b"2.0\n", 0o644),
        ("./control.tar.gz", gz(ctl), 0o644),
        ("./data.tar.gz", gz(data), 0o644),
    ])
    open(path, "wb").write(gz(outer))


def make_apk(path, arch, extra=()):
    data_tar = tar([
        ("www/luci-static/ctmodem/style.css", CSS, 0o644),
        ("usr/share/ucode/luci/template/themes/ctmodem/header.ut", TPL, 0o644),
        *extra,
    ])
    sig = tar([(".SIGN.RSA.test.rsa.pub", b"\x01" * 256, 0o644)])
    pkginfo = (
        "# Generated by abuild 3.14.0-r0\n"
        "pkgname = luci-theme-ctmodem\n"
        "pkgver = 26.293.25639~e74b366\n"
        "pkgdesc = CT modem theme for LuCI\n"
        "arch = %s\n"
        "size = %d\n"
        "origin = luci-theme-ctmodem\n"
        "commit = e74b366\n"
        "maintainer = someone <someone@example.com>\n"
        "license = Apache-2.0\n"
        "depend = luci-base\n"
        "datahash = %s\n"
    ) % (arch, len(data_tar), hashlib.sha256(data_tar).hexdigest())
    ctl = tar([
        (".PKGINFO", pkginfo.encode(), 0o644),
        (".post-install", b"#!/bin/sh\nrm -rf /tmp/luci-indexcache*\n", 0o755),
    ])
    open(path, "wb").write(gz(sig + ctl + data_tar))


make_ipk(os.path.join(FIX, "luci-theme-ctmodem_26.293_aarch64.ipk"), "aarch64_cortex-a53")
make_apk(os.path.join(FIX, "luci-theme-ctmodem-26.293_aarch64.apk"), "aarch64_cortex-a53")
make_ipk(os.path.join(FIX, "luci-theme-withlib_26.293_aarch64.ipk"), "aarch64_cortex-a53",
         extra=[("usr/lib/lua/luci/ctmodem/native.so", ELF64, 0o755)])
make_apk(os.path.join(FIX, "luci-theme-withlib-26.293_aarch64.apk"), "aarch64_cortex-a53",
         extra=[("usr/lib/lua/luci/ctmodem/native.so", ELF64, 0o755)])
print("fixtures written to", FIX)
for f in sorted(os.listdir(FIX)):
    print("  %-48s %6d bytes" % (f, os.path.getsize(os.path.join(FIX, f))))
